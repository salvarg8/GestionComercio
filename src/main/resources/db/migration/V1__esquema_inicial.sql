-- ---------------------------------------------------------------------
-- Índices únicos parciales
-- ---------------------------------------------------------------------

-- Baja lógica: el código interno (sin distinguir mayúsculas) y el código de
-- barras son únicos sólo entre los productos activos. Un producto dado de
-- baja libera sus códigos; para volver a habilitarlo no puede haber otro
-- activo que los use.
CREATE UNIQUE INDEX uk_productos_codigo_activo
    ON productos (lower(codigo)) WHERE estado_registro = 'ACTIVO';
CREATE UNIQUE INDEX uk_productos_codigo_barras_activo
    ON productos (codigo_barras) WHERE estado_registro = 'ACTIVO';

-- Cada usuario tiene a lo sumo una caja abierta.
CREATE UNIQUE INDEX uk_cajas_abierta_por_usuario
    ON cajas (usuario_id) WHERE estado_caja = 'ABIERTA';

-- Un movimiento de inventario se revierte una sola vez.
CREATE UNIQUE INDEX uk_movimientos_inventario_revertido
    ON movimientos_inventario (movimiento_revertido_id) WHERE movimiento_revertido_id IS NOT NULL;



-- La columna de la alícuota se llama "alicuotaiva" porque así la nombra la
-- estrategia de nombres de Spring a partir del campo alicuotaIVA.
CREATE TABLE productos (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado_registro         varchar(255)   NOT NULL,
    fecha_creacion          timestamp(6)   NOT NULL,
    fecha_modificacion      timestamp(6)   NOT NULL,
    usuario_creacion_id     bigint,
    usuario_modificacion_id bigint,
    codigo                  varchar(50)    NOT NULL,
    nombre                  varchar(150)   NOT NULL,
    descripcion             varchar(500),
    codigo_barras           varchar(20),
    precio_compra           numeric(12, 2) NOT NULL,
    precio_venta            numeric(12, 2) NOT NULL,
    stock                   numeric(15, 3) NOT NULL,
    version                 bigint         NOT NULL DEFAULT 0,
    stock_minimo            numeric(15, 3) NOT NULL,
    maneja_stock            boolean        NOT NULL,
    permite_stock_negativo  boolean        NOT NULL,
    unidad_medida           varchar(30)    NOT NULL,
    alicuotaiva             varchar(20)    NOT NULL,
    categoria_id            bigint         NOT NULL,
    marca_id                bigint         NOT NULL,
    proveedor_id            bigint         NOT NULL,
    CONSTRAINT ck_productos_precio_compra CHECK (precio_compra >= 0),
    CONSTRAINT ck_productos_precio_venta CHECK (precio_venta >= 0),
    CONSTRAINT ck_productos_stock_minimo CHECK (stock_minimo >= 0),
    CONSTRAINT ck_productos_stock_negativo CHECK (stock >= 0 OR permite_stock_negativo)
);



-- Repite en la base las reglas de MovimientoInventario#verificarConsistencia.
CREATE TABLE movimientos_inventario (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado_registro         varchar(255)   NOT NULL,
    fecha_creacion          timestamp(6)   NOT NULL,
    fecha_modificacion      timestamp(6)   NOT NULL,
    usuario_creacion_id     bigint,
    usuario_modificacion_id bigint,
    producto_id             bigint         NOT NULL,
    tipo                    varchar(20)    NOT NULL,
    cantidad                numeric(15, 3) NOT NULL,
    stock_anterior          numeric(15, 3) NOT NULL,
    stock_resultante        numeric(15, 3) NOT NULL,
    fecha                   timestamp(6)   NOT NULL,
    motivo                  varchar(255)   NOT NULL,
    motivo_ajuste           varchar(30),
    origen                  varchar(20)    NOT NULL DEFAULT 'MANUAL',
    origen_id               bigint,
    movimiento_revertido_id bigint,
    usuario_id              bigint         NOT NULL,
    CONSTRAINT ck_movimientos_inventario_cantidad CHECK (
        (tipo = 'ENTRADA' AND cantidad > 0)
        OR (tipo = 'SALIDA' AND cantidad < 0)
        OR (tipo = 'AJUSTE' AND cantidad <> 0)
    ),
    CONSTRAINT ck_movimientos_inventario_stock_resultante
        CHECK (stock_resultante = stock_anterior + cantidad),
    CONSTRAINT ck_movimientos_inventario_motivo CHECK (btrim(motivo) <> ''),
    CONSTRAINT ck_movimientos_inventario_motivo_ajuste
        CHECK ((tipo = 'AJUSTE') = (motivo_ajuste IS NOT NULL)),
    CONSTRAINT ck_movimientos_inventario_origen
        CHECK ((origen = 'MANUAL') = (origen_id IS NULL))
);



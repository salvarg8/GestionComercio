-- =====================================================================
-- V1: esquema inicial (COM31)
--
-- Reproduce el esquema que generaba Hibernate con ddl-auto=update y le
-- agrega lo que Hibernate no sabe expresar: índices únicos parciales para
-- la baja lógica, restricciones CHECK de negocio, claves foráneas con
-- nombre e índices para las búsquedas frecuentes.
--
-- Las columnas de enums son varchar sin CHECK de valores: el enum de Java
-- es la fuente de verdad, y agregarle un valor no debe exigir migración.
--
-- Los datos iniciales (empresa, permisos, rol y usuario administrador) los
-- crea DataInitializer al arrancar, no esta migración: los permisos salen
-- del enum PermisoCodigo y la contraseña del administrador se cifra con
-- BCrypt desde la aplicación.
--
-- Flyway corre cada migración en una transacción y PostgreSQL tiene DDL
-- transaccional: si algo falla, no queda nada a medias.
-- =====================================================================



-- =====================================================================
-- V7: facturación electrónica de ARCA (COM36.1)
--
-- - empresas.fecha_inicio_actividades: obligatoria en el comprobante
--   impreso.
-- - Las facturas no usan la numeración interna de ventas: su número lo da
--   ARCA dentro del punto de venta y queda en comprobantes_arca. Por eso
--   ventas.numero_comprobante pasa a ser null en las facturas.
-- - configuracion_arca: un único registro con el ambiente, el punto de
--   venta y el certificado (PKCS#12 cifrado; la clave no está en la base).
-- - tickets_acceso_arca: ticket del WSAA compartido por todas las PC hasta
--   que vence.
-- - comprobantes_arca: factura de cada venta y, si se anuló después de
--   autorizada, su nota de crédito. El número se asigna al enviarlo y sólo
--   se conserva si ARCA lo recibió (ENVIADO, a confirmar) o lo autorizó.
-- =====================================================================

ALTER TABLE empresas
    ADD COLUMN fecha_inicio_actividades date;

ALTER TABLE ventas
    ALTER COLUMN numero_comprobante DROP NOT NULL;

ALTER TABLE ventas
    ADD CONSTRAINT ck_ventas_numero_comprobante_factura
        CHECK ((tipo_comprobante IN ('FACTURA_A', 'FACTURA_B', 'FACTURA_C')) = (numero_comprobante IS NULL));


CREATE TABLE configuracion_arca (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado_registro         varchar(255) NOT NULL,
    fecha_creacion          timestamp(6) NOT NULL,
    fecha_modificacion      timestamp(6) NOT NULL,
    usuario_creacion_id     bigint,
    usuario_modificacion_id bigint,
    ambiente                varchar(255) NOT NULL,
    punto_venta             integer,
    habilitada              boolean      NOT NULL,
    certificado             bytea,
    certificado_titular     varchar(255),
    certificado_vencimiento timestamp(6),
    pedido_certificado      bytea,
    pedido_fecha            timestamp(6),
    CONSTRAINT fk_configuracion_arca_usuario_creacion
        FOREIGN KEY (usuario_creacion_id) REFERENCES usuarios (id),
    CONSTRAINT fk_configuracion_arca_usuario_modificacion
        FOREIGN KEY (usuario_modificacion_id) REFERENCES usuarios (id),
    CONSTRAINT ck_configuracion_arca_punto_venta
        CHECK (punto_venta IS NULL OR punto_venta BETWEEN 1 AND 99998),
    CONSTRAINT ck_configuracion_arca_certificado
        CHECK ((certificado IS NULL) = (certificado_vencimiento IS NULL)),
    CONSTRAINT ck_configuracion_arca_pedido
        CHECK ((pedido_certificado IS NULL) = (pedido_fecha IS NULL)),
    CONSTRAINT ck_configuracion_arca_habilitada
        CHECK (NOT habilitada OR (punto_venta IS NOT NULL AND certificado IS NOT NULL))
);


CREATE TABLE tickets_acceso_arca (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ambiente  varchar(255)                NOT NULL,
    cuit      varchar(15)                 NOT NULL,
    servicio  varchar(30)                 NOT NULL,
    token     text                        NOT NULL,
    sign      text                        NOT NULL,
    generado  timestamp(6) with time zone NOT NULL,
    vence     timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_tickets_acceso_arca UNIQUE (ambiente, cuit, servicio)
);


CREATE TABLE comprobantes_arca (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado_registro         varchar(255) NOT NULL,
    fecha_creacion          timestamp(6) NOT NULL,
    fecha_modificacion      timestamp(6) NOT NULL,
    usuario_creacion_id     bigint,
    usuario_modificacion_id bigint,
    venta_id                bigint       NOT NULL,
    tipo_comprobante        varchar(255) NOT NULL,
    comprobante_asociado_id bigint,
    estado                  varchar(255) NOT NULL,
    ambiente                varchar(255) NOT NULL,
    cuit_emisor             varchar(15)  NOT NULL,
    punto_venta             integer      NOT NULL,
    numero                  bigint,
    fecha                   date,
    cae                     varchar(14),
    vencimiento_cae         date,
    doc_tipo                integer,
    doc_nro                 bigint,
    condicion_iva_receptor  integer,
    importe_total           numeric(12, 2),
    importe_neto            numeric(12, 2),
    importe_iva             numeric(12, 2),
    importe_exento          numeric(12, 2),
    observaciones           text,
    fecha_proceso           timestamp(6),
    CONSTRAINT fk_comprobantes_arca_venta
        FOREIGN KEY (venta_id) REFERENCES ventas (id),
    CONSTRAINT fk_comprobantes_arca_asociado
        FOREIGN KEY (comprobante_asociado_id) REFERENCES comprobantes_arca (id),
    CONSTRAINT fk_comprobantes_arca_usuario_creacion
        FOREIGN KEY (usuario_creacion_id) REFERENCES usuarios (id),
    CONSTRAINT fk_comprobantes_arca_usuario_modificacion
        FOREIGN KEY (usuario_modificacion_id) REFERENCES usuarios (id),
    CONSTRAINT ck_comprobantes_arca_numero
        CHECK ((estado IN ('ENVIADO', 'AUTORIZADO')) = (numero IS NOT NULL)),
    CONSTRAINT ck_comprobantes_arca_cae
        CHECK ((estado = 'AUTORIZADO') = (cae IS NOT NULL AND vencimiento_cae IS NOT NULL)),
    CONSTRAINT ck_comprobantes_arca_enviado
        CHECK (numero IS NULL OR (fecha IS NOT NULL AND importe_total IS NOT NULL)),
    CONSTRAINT ck_comprobantes_arca_asociado
        CHECK ((tipo_comprobante LIKE 'NOTA_CREDITO_%') = (comprobante_asociado_id IS NOT NULL))
);

-- Un número de ARCA corresponde a un único comprobante.
CREATE UNIQUE INDEX uk_comprobantes_arca_numero
    ON comprobantes_arca (ambiente, cuit_emisor, punto_venta, tipo_comprobante, numero)
    WHERE numero IS NOT NULL;

-- Cada venta tiene a lo sumo una factura y una nota de crédito.
CREATE UNIQUE INDEX uk_comprobantes_arca_venta_tipo ON comprobantes_arca (venta_id, tipo_comprobante);

CREATE INDEX idx_comprobantes_arca_pendientes
    ON comprobantes_arca (estado)
    WHERE estado IN ('PENDIENTE', 'ENVIADO');

CREATE TABLE comprobantes_arca_iva (
    comprobante_arca_id bigint         NOT NULL,
    orden               integer        NOT NULL,
    alicuota_arca       integer        NOT NULL,
    base_imponible      numeric(12, 2) NOT NULL,
    importe             numeric(12, 2) NOT NULL,
    PRIMARY KEY (comprobante_arca_id, orden),
    CONSTRAINT fk_comprobantes_arca_iva_comprobante
        FOREIGN KEY (comprobante_arca_id) REFERENCES comprobantes_arca (id)
);

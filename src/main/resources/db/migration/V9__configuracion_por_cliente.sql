-- =====================================================================
-- V9: configuración por cliente (COM38)
--
-- 1. Parámetros generales del sistema: una sola fila, que se crea acá.
--    El formato del ticket reemplaza al ancho de ticket de la empresa (V4).
-- 2. Las ventas pueden quedar sin caja si la configuración no exige una
--    caja abierta para vender.
-- 3. Auditoría de las actualizaciones masivas de precios.
-- =====================================================================

CREATE TABLE configuracion (
    id                           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado_registro              varchar(255) NOT NULL,
    fecha_creacion               timestamp(6) NOT NULL,
    fecha_modificacion           timestamp(6) NOT NULL,
    usuario_creacion_id          bigint,
    usuario_modificacion_id      bigint,
    venta_exige_caja             boolean      NOT NULL DEFAULT true,
    stock_negativo_por_defecto   boolean      NOT NULL DEFAULT false,
    unidad_medida_por_defecto    varchar(30)  NOT NULL DEFAULT 'UNIDAD',
    forma_pago_por_defecto       varchar(30)  NOT NULL DEFAULT 'EFECTIVO',
    comprobante_por_defecto      varchar(30)  NOT NULL DEFAULT 'FACTURA',
    redondeo                     varchar(30)  NOT NULL DEFAULT 'SIN_REDONDEO',
    formato_ticket               varchar(30)  NOT NULL DEFAULT 'TERMICO_80',
    imprimir_logo                boolean      NOT NULL DEFAULT true,
    pie_comprobante              varchar(500),
    CONSTRAINT fk_configuracion_usuario_creacion
        FOREIGN KEY (usuario_creacion_id) REFERENCES usuarios (id),
    CONSTRAINT fk_configuracion_usuario_modificacion
        FOREIGN KEY (usuario_modificacion_id) REFERENCES usuarios (id)
);

-- La fila única, con el ancho de ticket que tenía la empresa.
INSERT INTO configuracion (estado_registro, fecha_creacion, fecha_modificacion, formato_ticket)
SELECT 'ACTIVO', now(), now(),
       coalesce((SELECT CASE ancho_ticket WHEN 'MM_58' THEN 'TERMICO_58' ELSE 'TERMICO_80' END
                 FROM empresas ORDER BY id LIMIT 1), 'TERMICO_80');

ALTER TABLE empresas
    DROP CONSTRAINT ck_empresas_ancho_ticket,
    DROP COLUMN ancho_ticket;

-- ---------------------------------------------------------------------
-- Ventas sin caja
-- ---------------------------------------------------------------------

ALTER TABLE ventas
    ALTER COLUMN caja_id DROP NOT NULL;

-- ---------------------------------------------------------------------
-- Actualizaciones masivas de precios
--
-- porcentaje        aumento (positivo) o rebaja (negativo) aplicado
-- precio            VENTA, COMPRA o AMBOS
-- redondeo          redondeo aplicado a los precios nuevos
-- categoria/marca/proveedor: filtros usados (null: todos)
-- ---------------------------------------------------------------------

CREATE TABLE actualizaciones_precios (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado_registro         varchar(255)  NOT NULL,
    fecha_creacion          timestamp(6)  NOT NULL,
    fecha_modificacion      timestamp(6)  NOT NULL,
    usuario_creacion_id     bigint,
    usuario_modificacion_id bigint,
    porcentaje              numeric(7, 2) NOT NULL,
    precio                  varchar(30)   NOT NULL,
    redondeo                varchar(30)   NOT NULL,
    categoria_id            bigint,
    marca_id                bigint,
    proveedor_id            bigint,
    filtro                  varchar(255)  NOT NULL,
    cantidad_productos      integer       NOT NULL,
    CONSTRAINT fk_actualizaciones_precios_usuario_creacion
        FOREIGN KEY (usuario_creacion_id) REFERENCES usuarios (id),
    CONSTRAINT fk_actualizaciones_precios_usuario_modificacion
        FOREIGN KEY (usuario_modificacion_id) REFERENCES usuarios (id),
    CONSTRAINT fk_actualizaciones_precios_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id),
    CONSTRAINT fk_actualizaciones_precios_marca FOREIGN KEY (marca_id) REFERENCES marcas (id),
    CONSTRAINT fk_actualizaciones_precios_proveedor FOREIGN KEY (proveedor_id) REFERENCES proveedores (id),
    CONSTRAINT ck_actualizaciones_precios_porcentaje CHECK (porcentaje > -100)
);

CREATE TABLE actualizaciones_precios_detalle (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actualizacion_id        bigint         NOT NULL,
    producto_id             bigint         NOT NULL,
    precio_compra_anterior  numeric(12, 2) NOT NULL,
    precio_compra_nuevo     numeric(12, 2) NOT NULL,
    precio_venta_anterior   numeric(12, 2) NOT NULL,
    precio_venta_nuevo      numeric(12, 2) NOT NULL,
    CONSTRAINT fk_actualizaciones_precios_detalle_actualizacion
        FOREIGN KEY (actualizacion_id) REFERENCES actualizaciones_precios (id),
    CONSTRAINT fk_actualizaciones_precios_detalle_producto
        FOREIGN KEY (producto_id) REFERENCES productos (id)
);

CREATE INDEX idx_actualizaciones_precios_detalle_actualizacion
    ON actualizaciones_precios_detalle (actualizacion_id);
CREATE INDEX idx_actualizaciones_precios_detalle_producto
    ON actualizaciones_precios_detalle (producto_id);
